package com.sakinah.app.feature.emotional

data class PropheticStory(
    val prophetName: String,
    val situation: String,
    val ayah: String,
    val lesson: String
)

object PropheticStoriesHelper {

    fun getStoryForEmotion(emotionKey: String): PropheticStory {
        return when (emotionKey) {
            "حزن" -> PropheticStory(
                prophetName = "يعقوب والنبي محمد عليهما الصلاة والسلام",
                situation = "حين اشتد الحزن على يعقوب بفقد يوسف قال: ﴿فَصَبْرٌ جَمِيلٌ﴾، وحين مات إبراهيم دمعت عين النبي ﷺ صابراً محتسباً.",
                ayah = "إِنَّمَا أَشْكُو بَثِّي وَحُزْنِي إِلَى اللَّهِ وَأَعْلَمُ مِنَ اللَّهِ مَا لَا تَعْلَمُونَ",
                lesson = "الحزن شعور بشري طبيعي؛ والسكينة تأتي حين تبث حزنك لله وحده دون جزع."
            )
            "هم" -> PropheticStory(
                prophetName = "يونس عليه السلام (ذو النون)",
                situation = "أحاطت به ظلمات ثلاث: ظلمة الليل، وظلمة البحر، وظلمة بطن الحوت، فنادى بأعظم كلمات التوحيد والتسبيح.",
                ayah = "فَنَادَىٰ فِي الظُّلُمَاتِ أَن لَّا إِلَٰهَ إِلَّا أَنتَ سُبْحَانَكَ إِنِّي كُنتُ مِنَ الظَّالِمِينَ",
                lesson = "مهما عظمت همومك وأحاطت بك الكروب، فمفتاح الفرج هو التسبيح والاعتراف بالافتقار إلى الله."
            )
            "خوف" -> PropheticStory(
                prophetName = "رسول الله ﷺ وأبو بكر في الغار",
                situation = "حين وقف المشركون على باب الغار خاف الصديق على النبي ﷺ، فأجابه بيقين هز أركان الخوف: «ما ظنك باثنين الله ثالثهما؟».",
                ayah = "إِذْ يَقُولُ لِصَاحِبِهِ لَا تَحْزَنْ إِنَّ اللَّهَ مَعَنَا ۖ فَأَنزَلَ اللَّهُ سَكِينَتَهُ عَلَيْهِ",
                lesson = "إذا استشعرت معية الله معك وحفظه لك، تلاشت كل مخاوف الدنيا."
            )
            "مرض" -> PropheticStory(
                prophetName = "أيوب عليه السلام",
                situation = "ابتلي في جسده وأهله وماله سنيناً طويلة، فلم يتسخط، بل توسل لله بأدب العبودية المطلق.",
                ayah = "وَأَيُّوبَ إِذْ نَادَىٰ رَبَّهُ أَنِّي مَسَّنِيَ الضُّرُّ وَأَنتَ أَرْحَمُ الرَّاحِمِينَ",
                lesson = "المرض رفعة للدرجات وتطهير للذنوب، وحسن الظن بالرحيم يفتح أبواب الشفاء."
            )
            "غضب" -> PropheticStory(
                prophetName = "موسى عليه السلام",
                situation = "حين رجع إلى قومه غضبان أسفاً وألقى الألواح، سكن غضبه وأخذ الألواح وتوجه إلى ربه مستغفراً له ولأخيه.",
                ayah = "وَلَمَّا سَكَتَ عَن مُّوسَى الْغَضَبُ أَخَذَ الْأَلْوَاحَ ۖ وَفِي نُسْخَتِهَا هُدًى وَرَحْمَةٌ",
                lesson = "الهدوء والصمت والتعوذ بالله يطفئ لهيب الغضب ويعيد لك رشادك."
            )
            "قلق" -> PropheticStory(
                prophetName = "أم موسى عليهما السلام",
                situation = "كادت تجزع قلقاً على رضيعها وهو في التابوت في اليم، فربط الله على قلبها وثبّتها بوعده الحق.",
                ayah = "وَأَصْبَحَ فُؤَادُ أُمِّ مُوسَىٰ فَارِغًا ۖ إِن كَادَتْ لَتُبْدِي بِهِ لَوْلَا أَن رَّبَطْنَا عَلَىٰ قَلْبِهَا",
                lesson = "اسأل الله أن يربط على قلبك ويسكن قلقك؛ فوعد الله دائماً مفعولاً."
            )
            "رزق" -> PropheticStory(
                prophetName = "مريم وزكريا عليهما السلام",
                situation = "كلما دخل عليها زكريا المحراب وجد عندها رزقاً، قالت هو من عند الله يرزق من يشاء بغير حساب، فهنالك دعا ربه بيقين.",
                ayah = "إِنَّ اللَّهَ يَرْزُقُ مَن يَشَاءُ بِغَيْرِ حِسَابٍ",
                lesson = "خزائن الله ملأى لا تنفد؛ فتوكل عليه ولا تشغل بالك بالأسباب وتنسى مسبب الأسباب."
            )
            "شكر" -> PropheticStory(
                prophetName = "سليمان عليه السلام",
                situation = "حين رأى النعم العظيمة والملك الذي لا ينبغي لأحد من بعده، قال هذا من فضل ربي ليبلوني أأشكر أم أكفر.",
                ayah = "هَٰذَا مِن فَضْلِ رَبِّي لِيَبْلُوَنِي أَأَشْكُرُ أَمْ أَكْفُرُ",
                lesson = "النعم تُحفظ وتزيد بالشكر والاعتراف بالمنعم جل جلاله."
            )
            else -> PropheticStory(
                prophetName = "الأنبياء والمرسلون جميعاً",
                situation = "كان دأب الأنبياء اللجوء إلى الصلاة والذكر عند كل نازلة أو كرب.",
                ayah = "وَاسْتَعِينُوا بِالصَّبْرِ وَالصَّلَاةِ ۚ وَإِنَّهَا لَكَبِيرَةٌ إِلَّا عَلَى الْخَاشِعِينَ",
                lesson = "الصلاة والذكر هما الملاذ الآمن لكل قلب يبحث عن الطمأنينة."
            )
        }
    }
}

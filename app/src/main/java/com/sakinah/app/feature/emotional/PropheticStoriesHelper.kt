package com.sakinah.app.feature.emotional

data class PropheticStory(
    val prophetName: String,
    val storyTitle: String,
    val summary: String,
    val keyLesson: String
)

object PropheticStoriesHelper {

    fun getStoryForEmotion(emotionKey: String): PropheticStory {
        return when (emotionKey) {
            "حزن" -> PropheticStory(
                prophetName = "النبي محمد ﷺ ويعقوب عليه السلام",
                storyTitle = "صبر يعقوب وعام الحزن",
                summary = "حين فقد يعقوب عليه السلام يوسف وبنيامين قال: ﴿إِنَّمَا أَشْكُو بَثِّي وَحُزْنِي إِلَى اللَّهِ﴾، وحين توفيت خديجة وأبو طالب سكب النبي ﷺ دمعه وقال: «إن العين تدمع والقلب يحزن ولا نقول إلا ما يرضي ربنا».",
                keyLesson = "الحزن شعور بشري مشروع، والشفاء منه يكون بتفويض الحزن وبثه لله وحده دون تسخط."
            )
            "هم" -> PropheticStory(
                prophetName = "يونس عليه السلام (ذا النون)",
                storyTitle = "تسبيح يونس في ظلمات الحوت",
                summary = "حين التقمه الحوت في ظلمات ثلاث: ظلمة الليل، وظلمة البحر، وظلمة بطن الحوت، لم ييأس بل نادى: ﴿لَّا إِلَٰهَ إِلَّا أَنتَ سُبْحَانَكَ إِنِّي كُنتُ مِنَ الظَّالِمِينَ﴾ فاستجاب الله له ونجاه من الغم.",
                keyLesson = "لا توجد هموم مستحيلة على الله؛ التسبيح والاعتراف بالتقصير يخرجانك من أضيق الحلقات."
            )
            "خوف" -> PropheticStory(
                prophetName = "رسول الله ﷺ والصديق رضي الله عنه",
                storyTitle = "موقف الغار وسكينة المعية",
                summary = "حين وقف المشركون على باب الغار وقال أبو بكر: لو نظر أحدهم تحت قدميه لرآنا، طمأنه النبي ﷺ بيقين راسخ: «ما ظنك باثنين الله ثالثهما؟ ﴿لَا تَحْزَنْ إِنَّ اللَّهَ مَعَنَا﴾» فأنزل الله سكينته عليه.",
                keyLesson = "إذا استشعرت معية الله وقدرته، تضاءل كل خوف في عينيك واستقرت السكينة في صدرك."
            )
            "مرض" -> PropheticStory(
                prophetName = "أيوب عليه السلام",
                storyTitle = "أدب أيوب في ابتلاء الجسد",
                summary = "ابتلي أيوب عليه السلام في جسده وأهله وماله سنيناً طويلة، فلم يتسخط، بل دعا بأعظم أدب: ﴿أَنِّي مَسَّنِيَ الضُّرُّ وَأَنتَ أَرْحَمُ الرَّاحِمِينَ﴾ فكشف الله ضره وعوضه أضعافاً.",
                keyLesson = "الألم والوجع كفارات ورفعة درجات، وحسن التوسل برحمة الله يعجل بالشفاء والعافية."
            )
            "غضب" -> PropheticStory(
                prophetName = "رسول الله ﷺ",
                storyTitle = "الحلم النبوي وإطفاء الغضب",
                summary = "جاء رجل إلى النبي ﷺ فقال: أوصني، قال: «لا تغضب» فردد مراراً قال: «لا تغضب». وعلّمنا ﷺ: «إذا غضب أحدكم فليسكت، فإن كان قائماً فليجلس، وإن كان جالساً فليضطجع».",
                keyLesson = "الشدة ليست بالصرعة وقوة البطش، إنما الشديد الذي يملك نفسه عند الغضب بالاستعاذة والسكون."
            )
            "قلق" -> PropheticStory(
                prophetName = "رسول الله ﷺ يوم بدر",
                storyTitle = "تضرع ليلة الفرقان",
                summary = "في ليلة بدر والمؤمنون قلة والعدو أضعاف، ظل النبي ﷺ قائماً يصلي ويناجي ربه حتى سقط رداؤه عن منكبيه، فأنزل الله الملائكة وألقى على قلوبهم النعاس أمنة منه.",
                keyLesson = "إذا أقلقك المستقبل أو خشيت أمراً، ألجئ ظهرك إلى الله بالدعاء الخاشع ينزل عليك سكينته."
            )
            "استخارة" -> PropheticStory(
                prophetName = "رسول الله ﷺ وصحابته الكرام",
                storyTitle = "الشورى والاستخارة واليقين بالقدر",
                summary = "كان النبي ﷺ يعلم صحابته الاستخارة في الأمور كلها كما يعلمهم السورة من القرآن، موقناً بأن الخير فيما اختاره الله لا فيما تهواه النفس العجولة.",
                keyLesson = "استخر واستشر ثم امضِ متوكلاً، واعلم أن ما أصابك لم يكن ليخطئك وما أخطأك لم يكن ليصيبك."
            )
            "رزق" -> PropheticStory(
                prophetName = "مريم عليها السلام وزكريا عليه السلام",
                storyTitle = "رزق المحراب الذي ألهم زكريا",
                summary = "كلما دخل عليها زكريا المحراب وجد عندها رزقاً، قال: يا مريم أنى لك هذا؟ قالت: ﴿هُوَ مِنْ عِندِ اللَّهِ ۖ إِنَّ اللَّهَ يَرْزُقُ مَن يَشَاءُ بِغَيْرِ حِسَابٍ﴾، فهنالك دعا زكريا ربه ورُزق بيحيى.",
                keyLesson = "الخزائن ملأى بفضل الله؛ ثق بالرازق واسأله من فضله بيقين تام."
            )
            else -> PropheticStory(
                prophetName = "سليمان عليه السلام",
                storyTitle = "شكر سليمان على عظيم النعم",
                summary = "حين سمع نملة تحذر قومها وسخر الله له الريح والجن قال: ﴿رَبِّ أَوْزِعْنِي أَنْ أَشْكُرَ نِعْمَتَكَ الَّتِي أَنْعَمْتَ عَلَيَّ وَعَلَىٰ وَالِدَيَّ وَأَنْ أَعْمَلَ صَالِحًا تَرْضَاهُ﴾.",
                keyLesson = "الشكر قيد النعم الموجودة وصيد النعم المفقودة، و﴿لَئِن شَكَرْتُمْ لَأَزِيدَنَّكُمْ﴾."
            )
        }
    }
}

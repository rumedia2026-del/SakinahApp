package com.sakinah.app.feature.emotional

object EmotionalPrescriptionHelper {

    data class Prescription(
        val ayahText: String,
        val ayahSurah: String,
        val duaText: String,
        val duaSource: String,
        val instantAction: String,
        val recitationTitle: String,
        val recitationUrl: String
    )

    fun getPrescription(emotionKey: String, intensity: Int): Prescription {
        return when (emotionKey) {
            "قلق" -> Prescription(
                ayahText = "الَّذِينَ آمَنُوا وَتَطْمَئِنُّ قُلُوبُهُم بِذِكْرِ اللَّهِ ۗ أَلَا بِذِكْرِ اللَّهِ تَطْمَئِنُّ الْقُلُوبُ",

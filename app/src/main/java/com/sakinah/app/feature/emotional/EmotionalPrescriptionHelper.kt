                duaSource = "سنن الترمذي (صحيح)",
                instantAction = "خذ نفساً عميقاً، والزم الصلاة على النبي ﷺ 10 مرات.",
                recitationTitle = "تلاوة الطمأنينة",
                recitationUrl = "https://server8.mp3quran.net/afs/001.mp3"
            )

                duaSource = "مسند أحمد (صحيح)",
                instantAction = if (intensity >= 3) "توضأ الآن وصلِّ ركعتين خاشعتين في خلوة تامة وافرغ قلبك لله بالدعاء." else "قم وتوضأ واشرب كوب ماء بتمهل، وردد: «لا حول ولا قوة إلا بالله» 10 مرات بيقين.",

                instantAction = "ضع يدك على صدرك وكرر: «حسبي الله لا إله إلا هو عليه توكلت وهو رب العرش العظيم» 7 مرات.",
                recitationTitle = "آيات السكينة والأمان - الشيخ مشاري العفاسي",
                recitationUrl = "https://server8.mp3quran.net/afs/048.mp3"
            )
            "هم" -> Prescription(
                ayahText = "فَإِنَّ مَعَ الْعُسْرِ يُسْرًا • إِنَّ مَعَ الْعُسْرِ يُسْرًا",
                ayahSurah = "سورة الشرح: 5-6",
                duaText = "اللَّهُمَّ رَحْمَتَكَ أَرْجُو فَلَا تَكِلْنِي إِلَى نَفْسِي طَرْفَةَ عَيْنٍ، وَأَصْلِحْ لِي شَأْنِي كُلَّهُ لَا إِلَهَ إِلَّا أَنْتَ.",
                duaSource = "سنن أبي داود (حسن)",
                instantAction = "اكتب كل ما يقلقك في ورقة أو في دفتر المناجاة أدناه، ثم فوّض أمر كل نقطة لله وقل: «أفوض أمري إلى الله إن الله بصير بالعباد».",

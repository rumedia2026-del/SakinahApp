            )
            "غضب" -> Prescription(
                ayahText = "وَالْكَاظِمِينَ الْغَيْظَ وَالْعَافِينَ عَنِ النَّاسِ ۗ وَاللَّهُ يُحِبُّ الْمُحْسِنِينَ",
                ayahSurah = "سورة آل عمران: 134",
                duaText = "أَعُوذُ بِاللَّهِ مِنَ الشَّيْطَانِ الرَّجِيمِ.",
                duaSource = "صحيح البخاري ومسلم",
                instantAction = "غيّر هيئتك فوراً: إن كنت قائماً فاجلس، وإن كنت جالساً فاضطجع. توضأ بماء بارد واصمت تماماً لمدة 5 دقائق.",

                duaText = "رَبِّ أَوْزِعْنِي أَنْ أَشْكُرَ نِعْمَتَكَ الَّتِي أَنْعَمْتَ عَلَيَّ وَعَلَىٰ وَالِدَيَّ وَأَنْ أَعْمَلَ صَالِحًا تَرْضَاهُ.",
                duaSource = "سورة النمل: 19",
                instantAction = "تذكر 3 نعم أنعم الله بها عليك اليوم واحمده عليها بصدق، واسجد سجدة شكر لله تعالى.",
                recitationTitle = "تلاوة الحمد والشكر - سورة النمل",
                recitationUrl = "https://server8.mp3quran.net/afs/027.mp3"
            )
            "استخارة" -> Prescription(
                ayahText = "وَعَسَىٰ أَن تَكْرَهُوا شَيْئًا وَهُوَ خَيْرٌ لَّكُمْ ۖ وَعَسَىٰ أَن تُحِبُّوا شَيْئًا وَهُوَ شَرٌّ لَّكُمْ ۗ وَاللَّهُ يَعْلَمُ وَأَنتُمْ لَا تَعْلَمُونَ",
                ayahSurah = "سورة البقرة: 216",
                duaText = "اللَّهُمَّ إِنِّي أَسْتَخِيرُكَ بِعِلْمِكَ، وَأَسْتَقْدِرُكَ بِقُدْرَتِكَ، وَأَسْأَلُكَ مِنْ فَضْلِكَ الْعَظِيمِ، فَإِنَّكَ تَقْدِرُ وَلَا أَقْدِرُ، وَتَعْلَمُ وَلَا أَعْلَمُ، وَأَنْتَ عَلَّامُ الْغُيُوبِ...",
                duaSource = "صحيح البخاري",
                instantAction = "صل ركعتين من غير الفريضة، واقرأ دعاء الاستخارة كاملاً، ثم امضِ فيما انشرح له صدرك متوكلاً على الله.",
                recitationTitle = "تلاوة التوكل واليقين - سورة طه",
                recitationUrl = "https://server8.mp3quran.net/afs/020.mp3"
            )
            "مرض" -> Prescription(
                ayahText = "وَإِذَا مَرِضْتُ فَهُوَ يَشْفِينِ",
                ayahSurah = "سورة الشعراء: 80",
                duaText = "أَذْهِبِ الْبَأْسَ رَبَّ النَّاسِ، وَاشْفِ أَنْتَ الشَّافِي، لَا شِفَاءَ إِلَّا شِفَاؤُكَ، شِفَاءً لَا يُغَادِرُ سَقَمًا.",

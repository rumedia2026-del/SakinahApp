                recitationUrl = "https://server8.mp3quran.net/afs/041.mp3"
            )
            else -> Prescription(
                ayahText = "أَلَا بِذِكْرِ اللَّهِ تَطْمَئِنُّ الْقُلُوبُ",
                ayahSurah = "سورة الرعد: 28",
